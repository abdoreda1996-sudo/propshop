/**
 * Generates prisma/schema.postgres.prisma from the SQLite schema.
 *
 *   node prisma/generate-postgres-schema.mjs
 *
 * The dev database is SQLite because it needs no service to run. Production must be
 * Postgres: SQLite permits exactly one writer for the whole file, and measured here at
 * 20k listings and 200 concurrent operations, mixed read+write reached a p95 of 7
 * seconds with every write queued behind one lock. That is the failure mode to avoid.
 *
 * Rather than maintain two schemas by hand — which drift — this derives the Postgres one
 * and applies the differences Postgres actually needs:
 *
 *   1. provider      sqlite -> postgresql
 *   2. text columns  long free text becomes @db.Text rather than varchar(191)
 *   3. money         Float -> Decimal(14,2). Float is binary floating point: 0.1 + 0.2
 *                    is not 0.3, and these columns hold offers and agreed prices.
 *   4. full text     a GIN trigram index on the searchable columns, which is what makes
 *                    `contains` stop being a sequential scan (155ms here and rising)
 *
 * Steps 1-3 are mechanical. Step 4 is emitted as SQL in migrations/postgres-init.sql,
 * because Prisma cannot express a trigram operator class in the schema language.
 */

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const source = readFileSync(join(here, "schema.prisma"), "utf8");

// --- 1. provider -----------------------------------------------------------
let out = source.replace(
  /datasource db \{[^}]*\}/s,
  `datasource db {
  provider  = "postgresql"
  url       = env("DATABASE_URL")
  // Pooled connection for the app, direct connection for migrations. Serverless and
  // multi-instance deployments exhaust Postgres connections without a pooler long
  // before they exhaust CPU.
  directUrl = env("DIRECT_DATABASE_URL")
}`,
);

// --- 2. long text ----------------------------------------------------------
// Prisma maps String to varchar(191) on some providers and text on Postgres; being
// explicit avoids a silent truncation on a description or a JSON blob.
const LONG_TEXT_FIELDS = [
  "descriptionAr",
  "descriptionEn",
  "geomJson",
  "metadataJson",
  "unitTypesJson",
  "installmentJson",
  "validationJson",
  "checklistJson",
  "profileJson",
  "shortlistJson",
  "slotsJson",
  "termsJson",
  "factorsJson",
  "body",
  "redactedBody",
  "detail",
  "note",
];
for (const field of LONG_TEXT_FIELDS) {
  out = out.replace(new RegExp(`^(\\s+${field}\\s+String\\??)(\\s*(?://.*)?)$`, "gm"), "$1 @db.Text$2");
}

// --- 3. money --------------------------------------------------------------
// Every column that holds currency. Float is wrong for money in the same way it is wrong
// everywhere: it cannot represent 0.01 exactly, and these figures become contracts.
const MONEY_FIELDS = [
  "price",
  "amount",
  "adminFee",
  "depositAmount",
  "closedPrice",
  "agreedPrice",
  "remainingToDeveloper",
  "maintenanceDue",
  "low",
  "mid",
  "high",
  "medianPricePerSqm",
];
for (const field of MONEY_FIELDS) {
  out = out.replace(
    new RegExp(`^(\\s+)${field}(\\s+)Float(\\??)(\\s+@default\\([^)]*\\))?`, "gm"),
    (_m, indent, gap, optional, def) =>
      `${indent}${field}${gap}Decimal${optional}${def ?? ""} @db.Decimal(14, 2)`,
  );
}

out =
  `// GENERATED by prisma/generate-postgres-schema.mjs — do not edit by hand.\n` +
  `// Edit schema.prisma and re-run the generator, or the two will drift.\n` +
  `//\n` +
  `// Apply with:\n` +
  `//   DATABASE_URL=... npx prisma migrate deploy --schema prisma/schema.postgres.prisma\n` +
  `//   psql "$DATABASE_URL" -f prisma/migrations/postgres-init.sql\n\n` +
  out;

writeFileSync(join(here, "schema.postgres.prisma"), out);

// --- 4. Postgres-only SQL --------------------------------------------------
const initSql = `-- Postgres-only objects Prisma cannot express in the schema language.
-- Apply AFTER \`prisma migrate deploy\`. Safe to re-run.

-- ---------------------------------------------------------------------------
-- Full-text search
-- ---------------------------------------------------------------------------
-- The search box uses \`contains\`, which becomes ILIKE '%term%'. A b-tree index cannot
-- serve a leading wildcard, so this is a sequential scan over every listing: measured at
-- 155ms on 20k rows on SQLite and getting linearly worse. A trigram GIN index makes it an
-- index lookup.
--
-- pg_trgm also gives fuzzy matching, which matters for Arabic transliteration: a buyer
-- typing "Mivida", "Mevida" or "ميفيدا" should reach the same compound.
CREATE EXTENSION IF NOT EXISTS pg_trgm;

CREATE INDEX IF NOT EXISTS listing_title_ar_trgm ON "Listing" USING gin ("titleAr" gin_trgm_ops);
CREATE INDEX IF NOT EXISTS listing_title_en_trgm ON "Listing" USING gin ("titleEn" gin_trgm_ops);
CREATE INDEX IF NOT EXISTS compound_name_ar_trgm ON "Compound" USING gin ("nameAr" gin_trgm_ops);
CREATE INDEX IF NOT EXISTS compound_name_en_trgm ON "Compound" USING gin ("nameEn" gin_trgm_ops);
CREATE INDEX IF NOT EXISTS area_name_ar_trgm     ON "Area"     USING gin ("nameAr" gin_trgm_ops);
CREATE INDEX IF NOT EXISTS area_name_en_trgm     ON "Area"     USING gin ("nameEn" gin_trgm_ops);

-- ---------------------------------------------------------------------------
-- Partial indexes for the hot public queries
-- ---------------------------------------------------------------------------
-- Every buyer-facing query filters status='live' AND trustLevel>=2. A partial index
-- covers only those rows, so it stays small and hot in memory even as drafts, rejected
-- and sold listings accumulate — which they will, faster than live ones.
CREATE INDEX IF NOT EXISTS listing_public_published
  ON "Listing" ("publishedAt" DESC)
  WHERE status = 'live' AND "trustLevel" >= 2;

CREATE INDEX IF NOT EXISTS listing_public_price
  ON "Listing" (price)
  WHERE status = 'live' AND "trustLevel" >= 2;

CREATE INDEX IF NOT EXISTS listing_public_purpose_published
  ON "Listing" (purpose, "publishedAt" DESC)
  WHERE status = 'live' AND "trustLevel" >= 2;

-- Unread-message badge: the overwhelming majority of messages are read, so index only
-- the unread ones.
CREATE INDEX IF NOT EXISTS message_unread
  ON "Message" ("conversationId", "senderId")
  WHERE "readAt" IS NULL;

-- Live offers: the offers inbox and the expiry sweep both look only at pending rows.
CREATE INDEX IF NOT EXISTS offer_pending
  ON "Offer" ("sellerId", "buyerId", "expiresAt")
  WHERE status = 'pending';

-- ---------------------------------------------------------------------------
-- Integrity that the application also enforces
-- ---------------------------------------------------------------------------
-- At most one cover photo per listing. src/lib/cover.ts maintains this in a transaction;
-- the constraint means a bug or a manual edit cannot leave two.
CREATE UNIQUE INDEX IF NOT EXISTS listing_media_single_cover
  ON "ListingMedia" ("listingId")
  WHERE "isCover" = true;

-- At most one live offer per (listing, buyer). offerService.ts enforces this; the
-- constraint makes a race impossible rather than unlikely.
CREATE UNIQUE INDEX IF NOT EXISTS offer_one_live_per_buyer
  ON "Offer" ("listingId", "buyerId")
  WHERE status = 'pending';
`;

mkdirSync(join(here, "migrations"), { recursive: true });
writeFileSync(join(here, "migrations", "postgres-init.sql"), initSql);

const moneyCount = (out.match(/@db\.Decimal\(14, 2\)/g) ?? []).length;
const textCount = (out.match(/@db\.Text/g) ?? []).length;
console.log("wrote prisma/schema.postgres.prisma");
console.log(`  ${moneyCount} money columns -> Decimal(14,2)`);
console.log(`  ${textCount} long-text columns -> @db.Text`);
console.log("wrote prisma/migrations/postgres-init.sql");
console.log(`  ${(initSql.match(/CREATE (UNIQUE )?INDEX/g) ?? []).length} Postgres-only indexes`);
